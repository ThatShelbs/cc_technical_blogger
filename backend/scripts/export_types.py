"""Generate frontend/src/api/types.gen.ts from the FastAPI OpenAPI schema.

Run after changing API models:  uv run python scripts/export_types.py
CI runs it with --check to make sure the committed types are current.
"""

from __future__ import annotations

import json
import sys
import tempfile
from pathlib import Path
from typing import Any

from proseferno.config import REPO_ROOT, Settings
from proseferno.main import create_app
from proseferno.secrets import MemorySecretStore
from proseferno.services import build_services

OUT = REPO_ROOT / "frontend" / "src" / "api" / "types.gen.ts"
SKIP = {"HTTPValidationError", "ValidationError"}


def ts(schema: dict[str, Any]) -> str:
    if "$ref" in schema:
        return str(schema["$ref"]).rsplit("/", 1)[-1]
    if "anyOf" in schema:
        return " | ".join(dict.fromkeys(ts(s) for s in schema["anyOf"]))
    if "enum" in schema:
        return " | ".join(json.dumps(v) for v in schema["enum"])
    if "const" in schema:
        return json.dumps(schema["const"])
    kind = schema.get("type")
    if kind == "string":
        return "string"
    if kind in ("integer", "number"):
        return "number"
    if kind == "boolean":
        return "boolean"
    if kind == "null":
        return "null"
    if kind == "array":
        inner = ts(schema.get("items", {}))
        return f"({inner})[]" if "|" in inner else f"{inner}[]"
    if kind == "object":
        if schema.get("properties"):
            return "{ " + "; ".join(prop(k, v, schema) for k, v in schema["properties"].items()) + " }"
        extra = schema.get("additionalProperties")
        return f"Record<string, {ts(extra) if isinstance(extra, dict) else 'unknown'}>"
    return "unknown"


def prop(name: str, schema: dict[str, Any], parent: dict[str, Any]) -> str:
    optional = "" if name in parent.get("required", []) else "?"
    return f"{name}{optional}: {ts(schema)}"


def render(openapi: dict[str, Any]) -> str:
    lines = ["// Generated by backend/scripts/export_types.py from the API schema. Do not edit by hand.", ""]
    for name, schema in sorted(openapi["components"]["schemas"].items()):
        if name in SKIP:
            continue
        if schema.get("type") == "object" or "properties" in schema:
            lines.append(f"export interface {name} {{")
            lines.extend(f"  {prop(key, sub, schema)};" for key, sub in schema.get("properties", {}).items())
            lines.append("}")
        else:
            lines.append(f"export type {name} = {ts(schema)};")
        lines.append("")
    return "\n".join(lines)


def main() -> int:
    with tempfile.TemporaryDirectory() as tmp:
        settings = Settings(data_dir=Path(tmp), _env_file=None)  # type: ignore[call-arg]
        services = build_services(settings, secrets=MemorySecretStore())
        content = render(create_app(settings, services).openapi())
        services.engine.dispose()
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != content:
            print(f"{OUT} is out of date. Run: uv run python scripts/export_types.py")
            return 1
        print("Types are up to date.")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(content, encoding="utf-8", newline="\n")
    print(f"Wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
